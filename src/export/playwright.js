/**
 * export/playwright.js — Playwright spec export.
 *
 * Converts a Testigator plan's E2E flows into standalone @playwright/test
 * spec files. Scope: flows only — perf budgets, a11y rules, fuzz targets and
 * visual baselines remain Testigator-native executor features (they need
 * the Testigator runtime; emitting them as plain specs would be dishonest
 * about what the export guarantees).
 *
 * Every exported bundle includes `testigator-healer.ts` — a TypeScript
 * port of the runtime's deterministic selector ladder (original selector →
 * data-testid/data-test/aria-label attribute lookups → getByRole → getByText).
 * Interaction steps (click/fill/select/check/…) are emitted through the
 * healer so exported specs self-heal selector drift exactly like the runtime.
 *
 * Multi-role: pass `storageStateByRole` ({ role: storageStatePath }) and the
 * exporter wraps flows in per-role `test.describe` blocks with
 * `test.use({ storageState })`. Flows carrying `auth` are emitted separately
 * as an auth-setup describe (replace them with recorded storage states for CI).
 */

import { parseTestPlan } from '../services/testPlan.js';

export const HEALER_FILENAME = 'testigator-healer.ts';

// ─── helpers ─────────────────────────────────────────────────────────

/** Escape a JS/TS single-quoted string literal body. */
function escTs(value) {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
}

/** Emit a value that may carry ${VAR} placeholders (resolved via qs() at runtime). */
function qVal(value) {
  if (typeof value !== 'string') return `'${escTs(String(value))}'`;
  return /\$\{[^}]+\}/.test(value) ? `qs('${escTs(value)}')` : `'${escTs(value)}'`;
}

/** Emit an optional timeout option object. */
function timeoutOpt(timeoutMs) {
  return timeoutMs != null ? `, { timeout: ${timeoutMs} }` : '';
}

function escapeRegExp(text) {
  return String(text).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function slugify(name) {
  const slug = String(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return slug || 'flow';
}

// ─── healer (TypeScript, ported from executors/selectorResolver.js) ───

function healerTs() {
  return `/**
 * testigator-healer.ts — self-healing selector helper for exported specs.
 *
 * Generated by Testigator's spec exporter. Import it next to your spec:
 *   import { qClick, qFill, qLocate, qs, qJsonPath } from './testigator-healer';
 *
 * The ladder mirrors Testigator's runtime resolver: original selector →
 * [data-testid=…] / [data-test=…] / [aria-label=…] (name derived from the
 * selector's id/class/name fragments) → getByRole(implied role, { name }) →
 * getByText(name). Deterministic — no AI, no guessing beyond the fragments
 * already present in the selector.
 */
import type { Page, Locator } from '@playwright/test';
import { expect } from '@playwright/test';

/** Resolve Testigator test-data placeholders: \${VAR} → process.env[VAR]. */
export function qs(value: string): string {
  return value.replace(/\\$\\{([^}]+)\\}/g, (_m, name) => process.env[name] ?? '');
}

const ROLE_HINTS: Array<[RegExp, string]> = [
  [/\\bbutton\\b|\\bbtn\\b/i, 'button'],
  [/\\b(link|anchor)\\b|\\ba\\b\\s*[.[#:]|a$/i, 'link'],
  [/\\b(checkbox|toggle)\\b/i, 'checkbox'],
  [/\\b(radio)\\b/i, 'radio'],
  [/\\b(combobox|dropdown|select)\\b/i, 'combobox'],
  [/\\b(input|field|textbox|email|password|search|username)\\b/i, 'textbox'],
];

export function extractSelectorName(selector: string): string | null {
  if (typeof selector !== 'string' || !selector.trim()) return null;
  const patterns = [
    /\\[data-testid=["']?([^\\]"' ]+)["']?\\]/i,
    /\\[data-test=["']?([^\\]"' ]+)["']?\\]/i,
    /#([A-Za-z_][\\w-]*)/,
    /\\[name=["']?([^\\]"' ]+)["']?\\]/i,
    /\\[aria-label=["']?([^\\]"' ]+)["']?\\]/i,
    /\\.([A-Za-z_][\\w-]*)/,
  ];
  for (const re of patterns) {
    const m = selector.match(re);
    if (m && m[1]) return m[1];
  }
  return null;
}

export function inferRoleFromSelector(selector: string): string | null {
  if (typeof selector !== 'string') return null;
  for (const [re, role] of ROLE_HINTS) {
    if (re.test(selector)) return role;
  }
  return null;
}

type Candidate = { selector?: string; role?: string; text?: string; name?: string; kind: 'original' | 'attr' | 'role' | 'text' };

export function buildFallbackCandidates(selector: string): Candidate[] {
  const candidates: Candidate[] = [];
  const name = extractSelectorName(selector);
  if (!name) return candidates;
  for (const attr of ['data-testid', 'data-test', 'aria-label']) {
    candidates.push({ selector: \`[\${attr}="\${name}"]\`, kind: 'attr' });
  }
  const role = inferRoleFromSelector(selector);
  if (role) candidates.push({ role, name, kind: 'role' });
  candidates.push({ text: name, kind: 'text' });
  return candidates;
}

function locatorForCandidate(page: Page, candidate: Candidate, originalSelector: string): Locator | null {
  switch (candidate.kind) {
    case 'original':
    case 'attr':
      return page.locator(candidate.kind === 'original' ? originalSelector : candidate.selector!);
    case 'role':
      return page.getByRole(candidate.role as any, { name: candidate.name });
    case 'text':
      return page.getByText(candidate.text!, { exact: false });
    default:
      return null;
  }
}

function describeCandidate(candidate: Candidate): string {
  switch (candidate.kind) {
    case 'original': return candidate.selector!;
    case 'attr': return candidate.selector!;
    case 'role': return \`getByRole('\${candidate.role}', { name: '\${candidate.name}' })\`;
    case 'text': return \`getByText('\${candidate.text}')\`;
    default: return String(candidate);
  }
}

/**
 * Resolve a selector to a live locator using the fallback ladder.
 * Returns null when nothing exists — the caller should fall back to
 * page.locator(original) so Playwright produces its familiar timeout error.
 */
export async function qLocate(page: Page, selector: string, existenceTimeoutMs = 1500): Promise<Locator | null> {
  if (!selector || !selector.trim()) return null;
  const candidates: Candidate[] = [{ selector, kind: 'original' }, ...buildFallbackCandidates(selector)];
  for (const candidate of candidates) {
    const locator = locatorForCandidate(page, candidate, selector);
    if (!locator) continue;
    try {
      const count = await Promise.race([
        locator.count(),
        new Promise<never>((_, reject) => setTimeout(() => reject(new Error('probe timeout')), existenceTimeoutMs)),
      ]);
      if (count > 0) return locator;
    } catch {
      // locator gone mid-probe or slow — try the next rung
    }
  }
  return null;
}

async function qTarget(page: Page, selector: string, timeoutMs?: number): Promise<Locator> {
  const loc = await qLocate(page, selector);
  return loc ?? page.locator(selector);
}

export async function qClick(page: Page, selector: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).click(timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qFill(page: Page, selector: string, value: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).fill(qs(value), timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qSelect(page: Page, selector: string, value: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).selectOption(qs(value), timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qCheck(page: Page, selector: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).check(timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qUncheck(page: Page, selector: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).uncheck(timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qHover(page: Page, selector: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).hover(timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qFocus(page: Page, selector: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).focus();
}
export async function qPress(page: Page, selector: string, key: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).press(key, timeoutMs ? { timeout: timeoutMs } : undefined);
}
export async function qUpload(page: Page, selector: string, path: string, timeoutMs?: number): Promise<void> {
  await (await qTarget(page, selector, timeoutMs)).setInputFiles(path, timeoutMs ? { timeout: timeoutMs } : undefined);
}

/** Walk a dot/bracket JSON path ('a.b[0].c') — port of the runtime readJsonPath. */
export function qJsonPath(obj: unknown, path: string): unknown {
  if (!path) return obj;
  const normalized = path.replace(/\\[(\\d+)\\]/g, '.$1');
  let cur: unknown = obj;
  for (const key of normalized.split('.')) {
    if (key === '') continue;
    if (cur == null) return undefined;
    cur = (cur as Record<string, unknown>)[key];
  }
  return cur;
}

/**
 * Assert the navigation status of a goto you captured yourself:
 *   const __resp = await page.goto(url);
 *   await qExpectStatus(__resp, 200);
 */
export async function qExpectStatus(response: { status: () => number } | null, status: number): Promise<void> {
  expect(response?.status(), \`navigation status\`).toBe(status);
}
`;
}

// ─── step emission ───────────────────────────────────────────────────

/**
 * Emit one flow step as TS lines.
 * @returns {{ lines: string[], needsRequest: boolean }}
 */
function emitStep(step, nextStep, indent) {
  const lines = [];
  let needsRequest = false;
  const pad = indent;
  switch (step.action) {
    case 'navigate': {
      const url = step.value || step.selector;
      // Pair navigate + assertStatus into a single captured goto.
      if (nextStep && nextStep.action === 'assertStatus') {
        lines.push(`${pad}const __resp = await page.goto(${qVal(url)}${timeoutOpt(step.timeoutMs)});`);
        lines.push(`${pad}await qExpectStatus(__resp, ${nextStep.status});`);
        lines.push(`${pad}// (paired: assertStatus ${nextStep.status} validated on the navigation response above)`);
        return { lines, needsRequest, consumedNext: true };
      }
      lines.push(`${pad}await page.goto(${qVal(url)}${timeoutOpt(step.timeoutMs)});`);
      break;
    }
    case 'click':
      lines.push(`${pad}await qClick(page, '${escTs(step.selector)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'fill':
      lines.push(`${pad}await qFill(page, '${escTs(step.selector)}', ${qVal(step.value)}${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'select':
      lines.push(`${pad}await qSelect(page, '${escTs(step.selector)}', ${qVal(step.value)}${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'check':
      lines.push(`${pad}await qCheck(page, '${escTs(step.selector)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'uncheck':
      lines.push(`${pad}await qUncheck(page, '${escTs(step.selector)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'hover':
      lines.push(`${pad}await qHover(page, '${escTs(step.selector)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'focus':
      lines.push(`${pad}await qFocus(page, '${escTs(step.selector)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'press':
      lines.push(`${pad}await qPress(page, '${escTs(step.selector)}', '${escTs(step.value)}'${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'upload':
      lines.push(`${pad}await qUpload(page, '${escTs(step.selector)}', ${qVal(step.value)}${timeoutOpt(step.timeoutMs)});`);
      break;
    case 'wait':
      if (step.ms != null) lines.push(`${pad}await page.waitForTimeout(${step.ms});`);
      else lines.push(`${pad}await page.locator('${escTs(step.selector)}').waitFor({ state: '${step.state || 'visible'}' });`);
      break;
    case 'assertVisible':
      lines.push(`${pad}await expect(page.locator('${escTs(step.selector)}')).toBeVisible(${timeoutOpt(step.timeoutMs).replace(', ', '')});`);
      break;
    case 'assertHidden':
      lines.push(`${pad}await expect(page.locator('${escTs(step.selector)}')).toBeHidden();`);
      break;
    case 'assertText':
      if (step.equals != null) lines.push(`${pad}await expect(page.locator('${escTs(step.selector)}')).toHaveText('${escTs(step.equals)}');`);
      else lines.push(`${pad}await expect(page.locator('${escTs(step.selector)}')).toContainText('${escTs(step.contains)}');`);
      break;
    case 'assertUrl':
      if (step.url != null) lines.push(`${pad}await expect(page).toHaveURL('${escTs(step.url)}');`);
      else if (step.urlContains != null) lines.push(`${pad}await expect(page).toHaveURL(new RegExp('${escTs(escapeRegExp(step.urlContains))}'));`);
      else lines.push(`${pad}await expect(page).toHaveURL(new RegExp('${escTs(step.urlMatches)}'));`);
      break;
    case 'assertStatus':
      // Standalone (previous step was not a navigate) — cannot be validated
      // in a plain spec without response capture; recorded honestly.
      lines.push(`${pad}// NOTE: standalone assertStatus(${step.status}) was skipped — in exported`);
      lines.push(`${pad}// specs, status validation pairs with the preceding navigate step.`);
      break;
    case 'api-request': {
      needsRequest = true;
      const resVar = '__res';
      const headers = step.headers && Object.keys(step.headers).length > 0
        ? `\n${pad}    headers: ${JSON.stringify(step.headers)},`
        : '';
      let data = '';
      if (step.body != null && step.body !== '') {
        let literal = step.body;
        try { literal = JSON.stringify(JSON.parse(step.body)); } catch { literal = JSON.stringify(step.body); }
        data = `\n${pad}    data: ${literal},`;
      }
      lines.push(`${pad}const ${resVar} = await request.fetch('${escTs(step.url)}', {`);
      lines.push(`${pad}    method: '${step.method}',${headers}${data}`);
      lines.push(`${pad}});`);
      if (step.expectStatus != null) {
        lines.push(`${pad}expect(${resVar}.status()).toBe(${step.expectStatus});`);
      }
      if (step.expectJsonPath != null) {
        lines.push(`${pad}const __json = await ${resVar}.json();`);
        lines.push(`${pad}expect(qJsonPath(__json, '${escTs(step.expectJsonPath)}'), 'json path ${escTs(step.expectJsonPath)}').toBeDefined();`);
      }
      if (step.saveAsVar != null) {
        lines.push(`${pad}// Testigator saved this response as run variable '${escTs(step.saveAsVar)}'`);
        lines.push(`${pad}// (in standalone specs, capture the value you need from ${resVar} manually).`);
      }
      break;
    }
    default:
      lines.push(`${pad}// unsupported step: ${JSON.stringify(step.action)}`);
  }
  return { lines, needsRequest };
}

// ─── flow emission ───────────────────────────────────────────────────

function emitFlowTest(flow, indent, isAuthSetup) {
  const lines = [];
  const pad = indent;
  const needsRequest = flow.steps.some((s) => s.action === 'api-request');
  const signature = needsRequest ? 'async ({ page, request }) => {' : 'async ({ page }) => {';

  lines.push(`${pad}test('${escTs(flow.name)}', ${signature}`);
  // First effective step: auto-goto startUrl unless the flow starts with navigate.
  let steps = [...flow.steps];
  let consumed = 0;
  if (steps.length > 0 && steps[0].action === 'navigate') consumed = 0; // starts with navigate — no auto-goto
  else {
    lines.push(`${pad}  await page.goto(${qVal(flow.startUrl)});`);
  }
  for (let i = consumed; i < steps.length; i++) {
    const next = i + 1 < steps.length ? steps[i + 1] : null;
    const { lines: emitted, consumedNext } = emitStep(steps[i], next, `${pad}  `);
    lines.push(...emitted);
    if (consumedNext) i += 1;
  }
  lines.push(`${pad}});`);
  return { lines, needsRequest };
}

// ─── plan emission ───────────────────────────────────────────────────

/**
 * Export a plan's flows as Playwright spec files.
 *
 * @param {object} plan — a Testigator TestPlan (raw object or parsed)
 * @param {object} [opts]
 * @param {string} [opts.source] — provenance note for the header comment
 * @param {Record<string, string>} [opts.storageStateByRole] — role → storageState path;
 *        when given, non-auth flows are wrapped in per-role describes with
 *        `test.use({ storageState })`. Auth flows always emit separately.
 * @returns {{ files: Array<{ name: string, content: string }>, notes: string[] }}
 */
export function exportPlaywrightSpecs(plan, opts = {}) {
  const parsed = parseTestPlan(plan); // normalize + validate
  const flows = parsed.flows || [];
  const notes = [];
  const files = [];

  const header = (flowName) => `/**
 * Exported by Testigator from plan '${escTs(parsed.id || 'unknown')}' (${parsed.status || 'unknown'})${opts.source ? ` — ${escTs(opts.source)}` : ''}.
 * Scope: E2E flows only — perf budgets, a11y rules, fuzz targets and visual
 * baselines remain Testigator-native executor features.
 * Flow: ${escTs(flowName)}
 */
import { test, expect } from '@playwright/test';
import { qClick, qFill, qSelect, qCheck, qUncheck, qHover, qFocus, qPress, qUpload, qJsonPath, qExpectStatus, qs } from './${HEALER_FILENAME.replace(/\.ts$/, '')}';
`;

  const authFlows = flows.filter((f) => f.auth);
  const normalFlows = flows.filter((f) => !f.auth);

  // Grouping: storageStateByRole → per-role describes for non-auth flows.
  const roles = opts.storageStateByRole ? Object.keys(opts.storageStateByRole) : null;

  for (const flow of normalFlows) {
    const body = emitFlowTest(flow, '  ', false);
    const fileLines = [header(flow.name)];
    if (roles) {
      for (const role of roles) {
        fileLines.push(`test.describe('${escTs(role)}', () => {`);
        fileLines.push(`  test.use({ storageState: '${escTs(opts.storageStateByRole[role])}' });`);
        if (flow.retry.maxAttempts > 1) {
          fileLines.push(`  test.describe.configure({ retries: ${flow.retry.maxAttempts - 1} });`);
        }
        fileLines.push(...emitFlowTest(flow, '  ', false).lines);
        fileLines.push('});');
      }
    } else {
      if (flow.retry.maxAttempts > 1) {
        fileLines.push(`test.describe.configure({ retries: ${flow.retry.maxAttempts - 1} });`);
      }
      fileLines.push(...body.lines);
    }
    // needsRequest propagation: when grouped, every emitted test needs it.
    const needsRequest = body.needsRequest || Boolean(roles);
    const content = fileLines.join('\n').replace(
      /async \(\{ page \}\) => \{/g,
      needsRequest ? 'async ({ page, request }) => {' : 'async ({ page }) => {'
    );
    files.push({ name: `${slugify(flow.name)}.spec.ts`, content });
  }

  if (authFlows.length > 0) {
    const lines = [
      header('auth setup'),
      '// Auth flows perform the recorded login. For CI, replace this describe',
      '// with recorded storage states (SessionStore export) via test.use().',
      "test.describe('auth setup — replace with recorded storage states for CI', () => {",
    ];
    for (const flow of authFlows) {
      if (flow.retry.maxAttempts > 1) {
        lines.push(`  test.describe.configure({ retries: ${flow.retry.maxAttempts - 1} });`);
      }
      lines.push(...emitFlowTest(flow, '  ', true).lines);
    }
    lines.push('});');
    files.push({ name: 'auth-setup.spec.ts', content: lines.join('\n') });
  }

  files.push({ name: HEALER_FILENAME, content: healerTs() });

  if (flows.length === 0) {
    notes.push('Plan has no flows — only the healer helper was exported.');
  }
  return { files, notes };
}
